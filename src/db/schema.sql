-- Esquema de AutoPedido 2.0 (PostgreSQL 14+, ej. Supabase).
-- Se ejecuta con search_path = esquema de la app (DB_SCHEMA, por defecto "eatsy"): todo lo que se
-- crea acá queda dentro de ese esquema y no toca otros proyectos de la misma base. Idempotente.
-- Las fechas se guardan en la hora local del negocio (APP_TIMEZONE), sin zona horaria.
-- Los "booleanos" son SMALLINT 0/1.

-- Texto normalizado para comparar y buscar sin distinguir mayúsculas ni tildes
-- (sin extensiones: la base puede ser compartida).
CREATE OR REPLACE FUNCTION norm(t text) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  AS $$ SELECT lower(translate(t, 'ÁÀÄÂÃÉÈËÊÍÌÏÎÓÒÖÔÕÚÙÜÛÑÇáàäâãéèëêíìïîóòöôõúùüûñç', 'aaaaaeeeeiiiiooooouuuuncaaaaaeeeeiiiiooooouuuunc')) $$;

CREATE TABLE IF NOT EXISTS usuarios (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(100) NOT NULL,
  contrasena  VARCHAR(255) NOT NULL,
  rol         VARCHAR(20)  NOT NULL CHECK (rol IN ('Administrador', 'Cajero', 'Cocina', 'Cliente', 'Mozo')),
  qr_token    VARCHAR(40)  NULL UNIQUE,          -- QR de las mesas del mozo (/mesa/<token>)
  activo      SMALLINT     NOT NULL DEFAULT 1,
  created_at  TIMESTAMP(0) NOT NULL,
  updated_at  TIMESTAMP(0) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_usuarios_nombre ON usuarios (norm(nombre));

-- Configuración de la instalación (la maneja el superadmin): paquete, licencia, marca, límites y módulos.
CREATE TABLE IF NOT EXISTS configuracion (
  clave       VARCHAR(50) PRIMARY KEY,
  valor       TEXT        NOT NULL,              -- JSON
  updated_at  TIMESTAMP(0) NOT NULL
);

-- Mesas abiertas por un mozo (aunque todavía no tengan pedidos). Cada apertura tiene un código
-- de 4 dígitos que el mozo le da al cliente para seguir la mesa desde el celular; al liberarla
-- (cerrada_at) el código y el acceso de esos celulares dejan de valer.
CREATE TABLE IF NOT EXISTS mesas_abiertas (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mozo_id     INTEGER      NOT NULL REFERENCES usuarios(id),
  numero      SMALLINT     NOT NULL CHECK (numero >= 0),
  codigo      CHAR(4)      NOT NULL,
  abierta_at  TIMESTAMP(0) NOT NULL,
  cerrada_at  TIMESTAMP(0) NULL
);
CREATE INDEX IF NOT EXISTS idx_mesas_numero ON mesas_abiertas (numero, cerrada_at);
CREATE INDEX IF NOT EXISTS idx_mesas_mozo ON mesas_abiertas (mozo_id, cerrada_at);

CREATE TABLE IF NOT EXISTS clientes (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(50)  NOT NULL,
  apellido    VARCHAR(50)  NOT NULL,
  cedula      VARCHAR(20)  NOT NULL UNIQUE,
  telefono    VARCHAR(20)  NULL,
  puntos      INTEGER      NOT NULL DEFAULT 0,
  activo      SMALLINT     NOT NULL DEFAULT 1,
  created_at  TIMESTAMP(0) NOT NULL,
  updated_at  TIMESTAMP(0) NOT NULL
);

CREATE TABLE IF NOT EXISTS categorias (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(255) NOT NULL,
  va_a_cocina SMALLINT     NOT NULL DEFAULT 1,   -- 0 = lo prepara/despacha la caja (bebidas, postres...)
  activo      SMALLINT     NOT NULL DEFAULT 1,
  created_at  TIMESTAMP(0) NOT NULL,
  updated_at  TIMESTAMP(0) NOT NULL
);

CREATE TABLE IF NOT EXISTS ingredientes (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       VARCHAR(255)  NOT NULL,
  descripcion  VARCHAR(500)  NOT NULL DEFAULT '',
  precio_extra NUMERIC(10,2) NULL,               -- precio por unidad extra (NULL = no se ofrece)
  activo       SMALLINT      NOT NULL DEFAULT 1,
  created_at   TIMESTAMP(0)  NOT NULL,
  updated_at   TIMESTAMP(0)  NOT NULL
);

CREATE TABLE IF NOT EXISTS productos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(255)  NOT NULL,
  descripcion TEXT          NOT NULL,
  precio      NUMERIC(10,2) NOT NULL CONSTRAINT chk_productos_precio CHECK (precio >= 0),
  imagen      VARCHAR(500)  NOT NULL,
  activo      SMALLINT      NOT NULL DEFAULT 1,
  created_at  TIMESTAMP(0)  NOT NULL,
  updated_at  TIMESTAMP(0)  NOT NULL
);

CREATE TABLE IF NOT EXISTS categoria_producto (
  producto_id  INTEGER NOT NULL REFERENCES productos(id)  ON DELETE CASCADE,
  categoria_id INTEGER NOT NULL REFERENCES categorias(id) ON DELETE CASCADE,
  PRIMARY KEY (producto_id, categoria_id)
);

CREATE TABLE IF NOT EXISTS ingrediente_producto (
  producto_id    INTEGER  NOT NULL REFERENCES productos(id)    ON DELETE CASCADE,
  ingrediente_id INTEGER  NOT NULL REFERENCES ingredientes(id) ON DELETE CASCADE,
  es_obligatorio SMALLINT NOT NULL DEFAULT 0,
  permite_extra  SMALLINT NOT NULL DEFAULT 1,     -- en este producto se puede pedir como extra
  PRIMARY KEY (producto_id, ingrediente_id)
);

CREATE TABLE IF NOT EXISTS promociones (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         VARCHAR(255)  NOT NULL,
  tipo_descuento VARCHAR(20)   NOT NULL DEFAULT 'porcentaje' CHECK (tipo_descuento IN ('porcentaje', 'monto')),
  descuento      NUMERIC(10,2) NOT NULL CONSTRAINT chk_promociones_descuento CHECK (descuento >= 0),
  codigo         VARCHAR(50)   NULL,
  fecha_inicio   DATE          NULL,
  fecha_fin      DATE          NULL,
  activo         SMALLINT      NOT NULL DEFAULT 1,
  created_at     TIMESTAMP(0)  NOT NULL,
  updated_at     TIMESTAMP(0)  NOT NULL
);

CREATE TABLE IF NOT EXISTS producto_promocion (
  producto_id  INTEGER NOT NULL REFERENCES productos(id)   ON DELETE CASCADE,
  promocion_id INTEGER NOT NULL REFERENCES promociones(id) ON DELETE CASCADE,
  PRIMARY KEY (producto_id, promocion_id)
);

CREATE TABLE IF NOT EXISTS pedidos (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id      INTEGER       NOT NULL REFERENCES usuarios(id),
  cliente_id      INTEGER       NULL REFERENCES clientes(id) ON DELETE SET NULL,
  promocion_id    INTEGER       NULL,             -- cupón aplicado (promoción con código)
  cupon_codigo    VARCHAR(30)   NULL,
  descuento_cupon NUMERIC(10,2) NOT NULL DEFAULT 0,
  origen          VARCHAR(10)   NOT NULL CHECK (origen IN ('Caja', 'Kiosco', 'Mozo')),
  mesa            SMALLINT      NULL,             -- solo pedidos tomados por un mozo
  mesa_abierta_id INTEGER       NULL REFERENCES mesas_abiertas(id) ON DELETE SET NULL,
  total           NUMERIC(10,2) NOT NULL DEFAULT 0,
  metodo_pago     VARCHAR(10)   NOT NULL CHECK (metodo_pago IN ('Efectivo', 'Tarjeta')),
  estado          VARCHAR(20)   NOT NULL CHECK (estado IN ('Cancelado', 'Recibido', 'En Preparacion', 'Listo', 'Entregado', 'En Mesa')),
  codigo          VARCHAR(20)   NOT NULL UNIQUE,
  created_at      TIMESTAMP(0)  NOT NULL,
  updated_at      TIMESTAMP(0)  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_pedidos_estado ON pedidos (estado);
CREATE INDEX IF NOT EXISTS idx_pedidos_created ON pedidos (created_at);
CREATE INDEX IF NOT EXISTS idx_pedidos_updated ON pedidos (updated_at);
CREATE INDEX IF NOT EXISTS idx_pedidos_mesa ON pedidos (usuario_id, mesa);
CREATE INDEX IF NOT EXISTS idx_pedidos_apertura ON pedidos (mesa_abierta_id);

CREATE TABLE IF NOT EXISTS detalle_pedido (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id       INTEGER       NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE,
  producto_id     INTEGER       NOT NULL REFERENCES productos(id),
  cantidad        INTEGER       NOT NULL CONSTRAINT chk_dp_cantidad CHECK (cantidad > 0),
  precio_unitario NUMERIC(10,2) NOT NULL,
  descuento       NUMERIC(10,2) NOT NULL DEFAULT 0,
  subtotal        NUMERIC(10,2) NOT NULL,
  para_cocina     SMALLINT      NOT NULL DEFAULT 1, -- se fija al pedir según las categorías del producto
  created_at      TIMESTAMP(0)  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_dp_pedido ON detalle_pedido (pedido_id);

CREATE TABLE IF NOT EXISTS detalle_pedido_ingrediente_quitado (
  detalle_pedido_id INTEGER NOT NULL REFERENCES detalle_pedido(id) ON DELETE CASCADE,
  ingrediente_id    INTEGER NOT NULL REFERENCES ingredientes(id),
  PRIMARY KEY (detalle_pedido_id, ingrediente_id)
);

CREATE TABLE IF NOT EXISTS detalle_pedido_ingrediente_extra (
  detalle_pedido_id INTEGER       NOT NULL REFERENCES detalle_pedido(id) ON DELETE CASCADE,
  ingrediente_id    INTEGER       NOT NULL REFERENCES ingredientes(id),
  cantidad          INTEGER       NOT NULL CONSTRAINT chk_dpie_cantidad CHECK (cantidad > 0),
  precio_unitario   NUMERIC(10,2) NOT NULL,
  PRIMARY KEY (detalle_pedido_id, ingrediente_id)
);

CREATE TABLE IF NOT EXISTS pagos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id   INTEGER       NOT NULL UNIQUE REFERENCES pedidos(id) ON DELETE CASCADE,
  tipo        VARCHAR(10)   NOT NULL CHECK (tipo IN ('Efectivo', 'Tarjeta')),
  monto       NUMERIC(10,2) NOT NULL,
  fecha       TIMESTAMP(0)  NOT NULL,
  estado      VARCHAR(12)   NOT NULL CHECK (estado IN ('Completado', 'Pendiente', 'Fallido')),
  created_at  TIMESTAMP(0)  NOT NULL,
  updated_at  TIMESTAMP(0)  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_pagos_fecha ON pagos (fecha);

CREATE TABLE IF NOT EXISTS punto_pedido (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id  INTEGER      NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
  pedido_id   INTEGER      NOT NULL REFERENCES pedidos(id)  ON DELETE CASCADE,
  cantidad    INTEGER      NOT NULL,
  tipo        VARCHAR(10)  NOT NULL CHECK (tipo IN ('Canjeo', 'Redencion')),
  fecha       TIMESTAMP(0) NOT NULL,
  created_at  TIMESTAMP(0) NOT NULL,
  CONSTRAINT uq_punto_pedido UNIQUE (pedido_id, tipo)
);

CREATE TABLE IF NOT EXISTS reglas_puntos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monto_min   NUMERIC(10,2) NOT NULL,
  monto_max   NUMERIC(10,2) NOT NULL,
  puntos_base INTEGER       NOT NULL,
  created_at  TIMESTAMP(0)  NOT NULL,
  updated_at  TIMESTAMP(0)  NOT NULL,
  CONSTRAINT chk_reglas_rango CHECK (monto_max > monto_min AND monto_min >= 0),
  CONSTRAINT chk_reglas_puntos CHECK (puntos_base >= 1)
);
